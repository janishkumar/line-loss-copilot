import { useEffect, useRef, useState, type FormEvent, type ReactNode } from "react";
import { Link } from "react-router-dom";
import { postChat, type ChatMessage, type ChatResult } from "../api";
import Citations from "../components/Citations";

const MAX_MESSAGES = 20;
const MAX_CHARS = 4000;
// [event:12], and the grouped forms small models write: [event:12, event:13] or [event:12, 13].
// The bracket body is a bounded class (no nested quantifiers), then checked by refIds.
const EVENT_REF = /\[event:([^[\]\n]{1,200})\]/g;
// Mirrors split_answer in src/linecopilot/chat/prompt.py: the marker counts on the last line only.
const ANSWER_TAIL = /(?:^|[ \t])ANSWER:[ \t]*([^\n]*?)[ \t]*$/;

/** Ids in one bracket body after "event:", or null if it is not a list of ids. */
export function refIds(body: string): string[] | null {
  const ids: string[] = [];
  for (const raw of body.split(",")) {
    let part = raw.trim();
    if (ids.length && part.startsWith("event:")) part = part.slice("event:".length).trim();
    if (!/^[0-9]+$/.test(part)) return null;
    ids.push(part);
  }
  return ids;
}

type Turn = { role: "user"; content: string } | { role: "assistant"; content: string; result: ChatResult };

/** The answer without its `ANSWER:` marker (kept for evals), which counts only on the last
 * line, on its own or after the text. If the marker is all the model wrote, its text is the
 * answer. */
export function visibleAnswer(answer: string): string {
  const text = answer.trimEnd();
  const cut = text.lastIndexOf("\n");
  const head = cut < 0 ? "" : text.slice(0, cut);
  const last = text.slice(cut + 1);
  const m = ANSWER_TAIL.exec(last);
  if (!m || !m[1]) return text.trim();
  const body = `${head}\n${last.slice(0, m.index)}`.trim();
  return body || m[1];
}

/** Plain text with each [event:N] turned into a link to that event's source rows. */
function withEventLinks(text: string): ReactNode[] {
  const out: ReactNode[] = [];
  let last = 0;
  for (const m of text.matchAll(EVENT_REF)) {
    const ids = refIds(m[1]);
    if (!ids) continue;
    out.push(text.slice(last, m.index));
    ids.forEach((id, j) => {
      if (j) out.push(", ");
      out.push(
        <Link key={`${m.index}-${j}`} to={`/evidence/${id}`} title="Source rows for this event">
          event {id}
        </Link>,
      );
    });
    last = (m.index ?? 0) + m[0].length;
  }
  out.push(text.slice(last));
  return out;
}

function Answer({ result }: { result: ChatResult }) {
  const unsupported = result.unsupported_cited_ids;
  return (
    <>
      <p className="answer">{withEventLinks(visibleAnswer(result.answer))}</p>
      {unsupported.length > 0 && (
        <div className="notice" role="alert">
          Cited {unsupported.length === 1 ? "event" : "events"} {unsupported.join(", ")} did not
          appear in any tool result. Treat those claims as unsupported.
        </div>
      )}
      <div className="meta">
        <span className="badge" title="Generated by a local model; check the cited rows">
          machine-generated · {result.model}
        </span>
        <Citations count={result.citation_count} citations={result.citations} />
      </div>
      <details className="trace">
        <summary>
          Tool trace ({result.tool_calls.length} {result.tool_calls.length === 1 ? "call" : "calls"},{" "}
          {result.rounds} {result.rounds === 1 ? "round" : "rounds"})
        </summary>
        {result.tool_calls.length === 0 ? (
          <p className="muted">No tools were called.</p>
        ) : (
          <ol>
            {result.tool_calls.map((t, i) => (
              <li key={i}>
                <strong>{t.name}</strong>{" "}
                <code>{typeof t.args === "string" ? t.args : JSON.stringify(t.args)}</code>{" "}
                <span className="muted">
                  {t.status}
                  {t.missing ? `: ${t.missing}` : ""}
                </span>
              </li>
            ))}
          </ol>
        )}
      </details>
    </>
  );
}

export default function Chat() {
  const [turns, setTurns] = useState<Turn[]>([]);
  const [draft, setDraft] = useState("");
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [elapsed, setElapsed] = useState(0);
  const live = useRef(true);
  useEffect(() => {
    live.current = true;
    return () => {
      live.current = false;
    };
  }, []);
  useEffect(() => {
    if (!pending) return;
    setElapsed(0);
    const t = setInterval(() => setElapsed((s) => s + 1), 1000);
    return () => clearInterval(t);
  }, [pending]);

  const send = (e: FormEvent) => {
    e.preventDefault();
    const q = draft.trim();
    if (!q || pending) return;
    const next: Turn[] = [...turns, { role: "user", content: q }];
    // empty turns would be rejected by the API, so they are left out of the history
    const messages: ChatMessage[] = next
      .filter((t) => t.content.trim())
      .slice(-MAX_MESSAGES)
      .map((t) => ({ role: t.role, content: t.content.slice(0, MAX_CHARS) }));
    if (messages[0]?.role === "assistant") messages.shift();
    setTurns(next);
    setDraft("");
    setError(null);
    setPending(true);
    postChat(messages)
      .then((r) => {
        if (live.current)
          setTurns((ts) => [...ts, { role: "assistant", content: visibleAnswer(r.answer), result: r }]);
      })
      .catch((err: Error) => live.current && setError(err.message))
      .finally(() => live.current && setPending(false));
  };

  return (
    <>
      <h2>Ask the copilot</h2>
      <p className="muted">
        Answers come from a local model that can only call the read-only tools. Every number
        should cite source events; check them before acting.
      </p>
      <section className="chat" aria-label="Conversation">
        {turns.map((t, i) => (
          <div key={i} className={`turn ${t.role}`}>
            {t.role === "user" ? (
              <p className="answer"><strong>You:</strong> {t.content}</p>
            ) : (
              <Answer result={t.result} />
            )}
          </div>
        ))}
        {pending && (
          <p className="muted" role="status">
            Thinking ({elapsed} s). Local answers take 10 to 60 s.
          </p>
        )}
        {error && (
          <div className="notice" role="alert">
            <strong>No answer.</strong> {error}
          </div>
        )}
      </section>
      <form className="chat-form" onSubmit={send}>
        <label className="muted" style={{ flex: 1, display: "flex", flexDirection: "column" }}>
          Question
          <textarea
            value={draft}
            maxLength={MAX_CHARS}
            onChange={(e) => setDraft(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === "Enter" && !e.shiftKey) send(e);
            }}
            placeholder="For example: what was the top stop reason on s_1 in March 2021?"
          />
        </label>
        <button type="submit" disabled={pending || !draft.trim()}>
          Send
        </button>
      </form>
    </>
  );
}
